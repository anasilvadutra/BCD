CREATE DATABASE BIBLIOTECA_CONECTA_ANA;
USE BIBLIOTECA_CONECTA_ANA;
CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(100) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT NOT NULL DEFAULT 0,
    CONSTRAINT CHK_QUANTIDADE_NAO_NEGATIVA CHECK (QUANTIDADE_DISPONIVEL>= 0)
);

CREATE TABLE EMPRESTIMO(
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUÇÃO DATE NULL,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT'ABERTO'
);
CREATE TABLE HISTORICO_EMPRESTIMOS (
    ID_HISTORICO INT AUTO_INCREMENT,
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_DEVOLUCAO DATETIME NULL,
    status VARCHAR(20) DEFAULT 'EMPRESTADO',
    CONSTRAINT pk_historico PRIMARY KEY (id_historico),
    CONSTRAINT fk_historico_usuario FOREIGN KEY (id_usuario) 
        REFERENCES USUARIO(id_usuario) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_historico_livro FOREIGN KEY (id_livro) 
        REFERENCES LIVRO(id_livro) 
        ON DELETE RESTRICT,
    CONSTRAINT chk_status CHECK (status IN ('EMPRESTADO', 'DEVOLVIDO', 'ATRASADO'))
);
