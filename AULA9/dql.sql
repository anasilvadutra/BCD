-- JOIN COM TRÊS TABELAS 
-- EX 22: ITENS DE PEDIDO COM NOME DO PRODUTO 
SELECT P.ID_PEDIDO, PR.NOME AS PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO, IP.QUALIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN ITEM_PEDIDO AS IP 
ON IP.ID_PEDIDO = P.ID_PEDIDO 
INNER JOIN PRODUTO AS PR 
ON PR.ID_PRODUTO = IP._PRODUTO 
ORDER BY P.ID_PEDIDO; 

-- EX 23: - AGREGAÇÃO + JOINS 
-- QUANTIDADES DE PRODUTOS POR CATEGORIAS 
SELECT CA.NOME AS CATEGORIA, COUNT(PR.ID_PRODUTO) AS QTDE_PRODUTOS
FROM CATEGORIA AS CA 
LEFT JOIN PRODUTO AS PR 
ON PR.ID_CATEGORIA = CA.ID_CATEGORIA 
GROUP BY CA.ID_CATEGOERIA , CA.NOME 
ORDER BY QTDE_PRODUTOS DESC; 

-- EX 24: TOTAL COMPRADO POR  CLIENTE 
SELECT C.NOME AS CLIENTE, COUNT(P.ID_PEDIDO) AS QTDE_PEDIDOS, SUM(P.VALOR_TOTAL) AS TOTAL_COMPLETO
FROM CLIENTE AS C 
INNER JOIN PEDIDO AS P 
ON P.CLIENTE = C.ID_CLIENTE 
WHERE P.STATUS = 'PREPARANDO'
GROUP BY C.ID_CLIENTE, C.NOME 
ORDER BY TOTAL_COMPRADO DESC;

-- RELATÓRIO COMPLETO DO PEDIDO
-- EX 25: COMBINAE VÁRIAS TABELAS EM UMA CONSULTA
SELECT P.ID_PEDIDO, DATE_FORMAT(P.DATA_PEDIDO, '%d %m %Y %H: %i') AS DATA, C.NOME AS CLIENTE, PR.NOME AS PRODUTO, IP.QUANTIDADE, IP.PRECO_UNITARIO, IP.QUANTIDADE * IP.PRECO_UNITARIO AS SUBTOTAL
FROM PEDIDO AS P 
INNER JOIN CLIENTE AS C 
ON C.ID_CLIENTE =  P.ID_CLIENTE 
INNER JOIN ITEM_PEDIDO AS P 
ON IP.ID_PEDIDO = P.ID_PEDIDO 
INNER JOIN PRODUTO AS PR 
ON PR.ID_PRODUTO = IP._ID_PRODUTO 
ORDER BY P.ID_PEDIDO, PR.NOME;

